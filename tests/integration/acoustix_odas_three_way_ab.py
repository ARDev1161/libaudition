#!/usr/bin/env python3
"""Three-way measured ODAS comparison: upstream, pinned dev and experiment.

Each input must be generated by a real offline WAV replay. This tool never
synthesizes metric values, and refuses to call incomplete SSS a PASS.
"""
import argparse
import json
from pathlib import Path
from acoustix_spatial_paired_ab import compare, METRICS

ROLES = ("upstream", "dev", "feature")
REQUIRED_PROVENANCE = ("odas_commit_sha", "odas_repository", "input_wav_sha256",
                       "oracle_sha256", "configuration_sha256", "case_id",
                       "input_frames", "sample_rate_hz")


def evaluate(replays):
    if set(replays) != set(ROLES):
        raise ValueError("require exactly upstream, dev and feature replays")
    for role in ROLES:
        row = replays[role]
        if not all(key in row for key in REQUIRED_PROVENANCE):
            raise ValueError("missing measured replay provenance for " + role)
        sha = row["odas_commit_sha"]
        if not isinstance(sha, str) or len(sha) != 40 or any(
                c not in "0123456789abcdef" for c in sha):
            raise ValueError("invalid ODAS commit SHA: " + role)
        if not isinstance(row["odas_repository"], str) or not row["odas_repository"]:
            raise ValueError("missing ODAS repository: " + role)
    if len({replays[r]["odas_commit_sha"] for r in ROLES}) != 3:
        raise ValueError("upstream/dev/feature must have three distinct commits")
    if replays["dev"]["odas_repository"] != replays["feature"]["odas_repository"]:
        raise ValueError("feature and dev must belong to the same ODAS fork")
    upstream_dev = compare(replays["upstream"], replays["dev"])
    dev_feature = compare(replays["dev"], replays["feature"])
    upstream_feature = compare(replays["upstream"], replays["feature"])
    comparisons = {"upstream_to_dev": upstream_dev,
                   "dev_to_feature": dev_feature,
                   "upstream_to_feature": upstream_feature}
    complete = all(v["complete"] for v in comparisons.values())
    # Directional comparisons are descriptive; no unspecified statistical
    # tolerance or physical feasibility threshold is silently invented.
    regressions = dev_feature["regressions"]
    status = ("BLOCKED_MISSING_METRICS" if not complete else
              "REGRESSIONS_VS_DEV" if regressions else
              "MEASURED_NO_REGRESSIONS_VS_DEV")
    return {"schema": "libaudition.acoustix-odas-three-way-ab.v1",
            "case_id": replays["dev"]["case_id"],
            "commits": {role: replays[role]["odas_commit_sha"] for role in ROLES},
            "status": status, "complete": complete,
            "comparisons": comparisons,
            "quality_accepted": False,
            "note": "Requires independent frozen held-out acceptance review; no automatic quality PASS."}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for role in ROLES:
        p.add_argument("--" + role, required=True, type=Path)
    p.add_argument("--output", required=True, type=Path)
    a = p.parse_args()
    rows = {r: json.loads(getattr(a, r).read_text()) for r in ROLES}
    result = evaluate(rows)
    a.output.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(result["status"])
    return 2 if not result["complete"] else 1 if result["status"] == "REGRESSIONS_VS_DEV" else 0


if __name__ == "__main__":
    raise SystemExit(main())
